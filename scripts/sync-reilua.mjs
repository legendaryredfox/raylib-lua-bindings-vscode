// Generates src/reilua.ts from ReiLua's ReiLua_API.lua (LuaLS annotations).
// Usage: node scripts/sync-reilua.mjs [path/to/ReiLua_API.lua]   (default ../ReiLua/ReiLua_API.lua)
// Add --check to only report whether src/reilua.ts is up to date.
// Add --binary <path/to/ReiLua> to also compare against the live `RL` table (runs `ReiLua -i` in a temp dir; no window opens).
import { spawnSync } from "node:child_process";
import os from "node:os";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const binIndex = args.indexOf("--binary");
const binary = binIndex >= 0 ? path.resolve(args[binIndex + 1]) : undefined;
const input = args.find((a, i) => !a.startsWith("--") && i !== binIndex + 1) ?? path.resolve(root, "../ReiLua/ReiLua_API.lua");
const output = path.join(root, "src/reilua.ts");
// Documented in ReiLua_API.lua and implemented in C, but never registered in the RL table (ReiLua v1.0).
const NOT_REGISTERED = new Set(["GetSoundStream", "rlEnableStatePointer", "rlDisableStatePointer"]);
// Globals that show up in the RL table when running `ReiLua -i`.
const INTERPRETER_ONLY = new Set(["arg"]);
const LIFECYCLE = new Set(["init", "update", "draw", "event", "log", "exit", "config"]);

const lines = fs.readFileSync(input, "utf8").split(/\r?\n/);
const fns = new Map();
const callbacks = new Map();
const consts = new Map();
let group = "Other";
let doc = [];

for (const line of lines) {
  if (line.startsWith("---")) {
    doc.push(line);
    continue;
  }
  const header = line.match(/^-- (?:Defines - )?(.+?)\.?\s*$/);
  if (header && !line.startsWith("-- Put this")) {
    group = header[1];
    doc = [];
    continue;
  }
  const fn = line.match(/^function\s+RL\.(\w+)\s*\(([^)]*)\)/);
  if (fn) {
    const [, name, rawParams] = fn;
    const target = LIFECYCLE.has(name) ? callbacks : fns;
    if (!target.has(name) && !NOT_REGISTERED.has(name)) {
      const params = rawParams.split(",").map(p => p.trim()).filter(p => p && p !== "...");
      const text = doc.find(d => !d.startsWith("---@") && !d.startsWith("---- "));
      const detail = (text ? text.slice(3) : name).trim().replace(/\s+/g, " ");
      const types = new Map(
        doc.map(d => d.match(/^---@param\s+(\w+)\s+(\S+)/)).filter(Boolean).map(m => [m[1], m[2]])
      );
      const paramTypes = params.map(p => types.get(p) ?? "any");
      const returns = doc
        .map(d => d.match(/^---- (Success|Failure) return (.+?)\s*$/))
        .filter(Boolean)
        .map(m => `${m[1]}: ${m[2]}`)
        .join("; ");
      target.set(name, [name, detail, params, paramTypes, returns]);
    }
    doc = [];
    continue;
  }
  const c = line.match(/^RL\.(\w+)\s*=\s*(-?[0-9][0-9.eE+-]*|\{[^}]*\})\s*$/);
  if (c && !consts.has(c[1])) {
    const value = c[2].startsWith("{") ? c[2].replace(/,/g, ", ") : Number(c[2]);
    consts.set(c[1], [c[1], group, value]);
  }
  doc = [];
}

const q = s => JSON.stringify(s);
const body = `// GENERATED by scripts/sync-reilua.mjs from ReiLua_API.lua — do not edit.
// Run \`node scripts/sync-reilua.mjs\` after ReiLua changes.

export type ReiLuaFunction = [name: string, detail: string, params: string[], paramTypes: string[], returns: string];
export type ReiLuaConstant = [name: string, group: string, value: number | string];

export const reiluaFunctions: ReiLuaFunction[] = [
${[...fns.values()].map(([n, d, p, t, r]) => `  [${q(n)}, ${q(d)}, [${p.map(q).join(", ")}], [${t.map(q).join(", ")}], ${q(r)}],`).join("\n")}
];

/** Functions ReiLua calls on your code (\`function RL.update( delta ) ... end\`). */
export const reiluaCallbacks: ReiLuaFunction[] = [
${[...callbacks.values()].map(([n, d, p, t, r]) => `  [${q(n)}, ${q(d)}, [${p.map(q).join(", ")}], [${t.map(q).join(", ")}], ${q(r)}],`).join("\n")}
];

export const reiluaConstants: ReiLuaConstant[] = [
${[...consts.values()].map(([n, g, v]) => `  [${q(n)}, ${q(g)}, ${typeof v === "number" ? v : q(v)}],`).join("\n")}
];
`;

/** Compare generated names with what the built ReiLua exposes at runtime. Returns true when they agree. */
function compareLive() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "reilua-dump-"));
  try {
    fs.writeFileSync(
      path.join(dir, "dump.lua"),
      'for k, v in pairs(RL) do print((type(v) == "function" and "F " or "C ") .. k) end'
    );
    const run = spawnSync(binary, ["-i", "dump.lua"], { cwd: dir, encoding: "utf8", timeout: 30000 });
    if (run.status !== 0 && !run.stdout) {
      console.log(`could not run ${binary}: ${run.stderr || run.error}`);
      return false;
    }
    const liveF = new Set(), liveC = new Set();
    for (const l of run.stdout.split("\n")) {
      if (l.startsWith("F ")) liveF.add(l.slice(2).trim());
      else if (l.startsWith("C ")) liveC.add(l.slice(2).trim());
    }
    const known = new Set([...fns.keys(), ...callbacks.keys()]);
    const missingFns = [...liveF].filter(n => !fns.has(n) && !INTERPRETER_ONLY.has(n));
    const staleFns = [...fns.keys()].filter(n => !liveF.has(n));
    const missingConsts = [...liveC].filter(n => !consts.has(n) && !INTERPRETER_ONLY.has(n));
    const staleConsts = [...consts.keys()].filter(n => !liveC.has(n));
    console.log(`live module: ${liveF.size} functions, ${liveC.size} constants`);
    const show = (label, list) => list.length && console.log(`${label} (${list.length}): ${list.join(" ")}`);
    show("in module, not in annotations", [...missingFns, ...missingConsts].filter(n => !known.has(n)));
    show("in annotations, not in module", [...staleFns, ...staleConsts]);
    return !missingFns.length && !staleFns.length && !missingConsts.length && !staleConsts.length;
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

console.log(`ReiLua: ${fns.size} functions, ${callbacks.size} callbacks, ${consts.size} constants`);
if (binary && !compareLive()) {
  console.log("annotations and live module differ");
  if (check) process.exit(1);
}
if (check) {
  const same = fs.existsSync(output) && fs.readFileSync(output, "utf8") === body;
  console.log(same ? "src/reilua.ts up to date" : "src/reilua.ts is out of date");
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(output, body);
console.log("wrote src/reilua.ts");
